import hashlib
import json
import zipfile
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import AsyncMock

import pytest

from wuwa_story_worker import cutscene_import, wwise_banks

FIXTURE = Path(__file__).parent / 'fixtures/cutscene-language-states.zip'
EVENTS = ('play_all_sound_c0026', 'play_all_sound_m3_6_26', 'play_all_sound_c0032')


@pytest.mark.parametrize('event', EVENTS)
@pytest.mark.parametrize('bank_locale', ['en', 'ja'])
@pytest.mark.parametrize('requested_locale', ['en', 'ja', 'ko', 'zh'])
def test_real_cutscene_states_bind_explicit_audio_language_not_bank_path_or_default(
    tmp_path, event, bank_locale, requested_locale,
):
    with zipfile.ZipFile(FIXTURE) as archive:
        name = f'xml/{bank_locale}/{event}.xml'
        data = archive.read(name)
        assert hashlib.sha256(data).hexdigest() == json.loads(archive.read('source.json'))['hashes'][name]
    xml = tmp_path / 'bank.xml'
    xml.write_bytes(data)
    assert wwise_banks.rover_parameters(xml, None, language=requested_locale) == [
        f'(2441027675={wwise_banks.event_id(requested_locale)})']
    assert all('748895195' not in p for p in wwise_banks.rover_parameters(xml, None, language=requested_locale))


@pytest.mark.parametrize('language', [None, '', 'zh-Hans', 'unverified'])
def test_language_selector_requires_explicit_supported_locale(tmp_path, language):
    with zipfile.ZipFile(FIXTURE) as archive:
        data = archive.read('xml/en/play_all_sound_c0026.xml')
    xml = tmp_path / 'bank.xml'
    xml.write_bytes(data)
    with pytest.raises(ValueError, match='explicit audio language'):
        wwise_banks.rover_parameters(xml, 'female', language=language)


def test_unavailable_state_and_unknown_selector_never_choose_a_default(tmp_path):
    xml = tmp_path / 'bank.xml'
    xml.write_text('''<root><object name="CAkSwitchCntr">
      <field name="ulGroupID" value="2441027675"/><field name="eGroupType" value="1"/>
      <field name="ulSwitchID" value="1467418007"/><field name="ulSwitchID" value="748895195"/>
    </object></root>''')
    with pytest.raises(ValueError, match='absent from the authored State'):
        wwise_banks.rover_parameters(xml, None, language='en')
    xml.write_text(xml.read_text().replace('2441027675', '3533944365'))
    assert wwise_banks.rover_parameters(xml, None, language='en') == []


def test_language_and_rover_bindings_remain_independent(tmp_path):
    xml = tmp_path / 'bank.xml'
    xml.write_text('''<root>
      <object name="CAkSwitchCntr"><field name="ulGroupID" value="2441027675"/>
        <field name="eGroupType" value="1"/><field name="ulSwitchID" value="1735860046"/></object>
      <object name="CAkSwitchCntr"><field name="ulGroupID" value="3313202977"/>
        <field name="eGroupType" value="1"/><field name="ulSwitchID" value="3111576190"/>
        <field name="ulSwitchID" value="2204441813"/></object>
    </root>''')
    assert wwise_banks.rover_parameters(xml, 'female', language='ja') == [
        '(2441027675=1735860046)', '(3313202977=2204441813)']
    with pytest.raises(ValueError, match='authored Rover'):
        wwise_banks.rover_parameters(xml, None, language='ja')
    xml.write_text(xml.read_text().replace('eGroupType" value="1"', 'eGroupType" value="0"', 1))
    with pytest.raises(ValueError, match='Unsupported Wwise language State'):
        wwise_banks.rover_parameters(xml, 'female', language='ja')


@pytest.mark.asyncio
async def test_renderer_passes_language_state_and_uses_separate_locale_workspaces(tmp_path, monkeypatch):
    bank = tmp_path / 'play_scene.bnk'
    bank.write_bytes(b'same authored bank')
    renderer, wem = tmp_path / 'wwiser.pyz', tmp_path / '123.wem'
    renderer.write_bytes(b'fixed tool')
    wem.write_bytes(b'fixed source')
    monkeypatch.setattr(wwise_banks, 'tool_path', lambda _: renderer)
    monkeypatch.setattr(cutscene_import, 'soundtrack_wem', lambda *_: wem)
    commands = []

    async def run(args, timeout):
        commands.append(args)
        if '-dn' in args:
            with zipfile.ZipFile(FIXTURE) as archive:
                Path(args[args.index('-dn') + 1] + '.xml').write_bytes(
                    archive.read('xml/en/play_all_sound_c0026.xml'))
        elif '-go' in args:
            assert '-gp' in args
            assert any(value.startswith('(2441027675=') for value in args[args.index('-gp')+1:])
            (Path(args[args.index('-go')+1])/'selected.txtp').write_text('wem/123.wem #i\n# AUTOGENERATED')
        else:
            Path(args[args.index('-o')+1]).write_bytes(b'RIFF' + b'x'*48)
        return SimpleNamespace(stderr=b'')

    outputs = []
    for locale in ('en', 'ja'):
        output, _ = await wwise_banks.render_bank(bank, tmp_path/'audio', tmp_path/'work',
            tmp_path/'decoder', None, run, language=locale)
        outputs.append(output)
    assert outputs[0] != outputs[1] and all(path.is_file() for path in outputs)
    generated = [args for args in commands if '-gp' in args]
    assert '(2441027675=1819748192)' in generated[0]
    assert '(2441027675=1735860046)' in generated[1]


@pytest.mark.asyncio
@pytest.mark.parametrize('authored_event', [True, False])
async def test_soundtrack_forwards_locale_and_does_not_reuse_other_language_decode(tmp_path, monkeypatch, authored_event):
    bank = tmp_path/'scene.bnk'
    bank.write_bytes(b'bank')
    monkeypatch.setattr(cutscene_import, 'has_authored_event', lambda *_: authored_event)
    if not authored_event:
        def multiple(*args):
            raise ValueError('Multiple music sources')
        monkeypatch.setattr(cutscene_import, 'bank_media_id', multiple)
    render = AsyncMock(return_value=(tmp_path/'decoded.wav', []))
    monkeypatch.setattr(cutscene_import, 'render_bank', render)
    decoded = {}
    for language in ('en', 'ja', 'en'):
        track = SimpleNamespace(bank='scene.bnk', media_id=None, rover=None, language=language)
        await cutscene_import.decode_soundtrack(track, tmp_path, tmp_path, tmp_path, tmp_path/'decoder', decoded)
    assert render.await_count == 2 and len(decoded) == 2
    assert [call.kwargs['language'] for call in render.await_args_list] == ['en', 'ja']
