import struct
from types import SimpleNamespace

import pytest

from wuwa_story_worker import wwise_banks


def bank(objects):
    content = struct.pack("<I", len(objects)) + b"".join(bytes([kind]) + struct.pack("<I", len(data)) + data
                                                       for kind, data in objects)
    return b"BKHD" + struct.pack("<II", 4, 172) + b"HIRC" + struct.pack("<I", len(content)) + content


def source(identity):
    return struct.pack("<IBIIIB", 0x00140001, 2, identity, 7, 10, 8)


def test_collects_music_and_both_rover_sources_without_choosing_one():
    data = bank([(2, struct.pack("<I", 1) + source(101)),
                 (2, struct.pack("<I", 2) + source(202)),
                 (11, struct.pack("<II", 3, 2) + source(303) + source(404))])
    assert wwise_banks.bank_media_ids(data) == [101, 202, 303, 404]
    with pytest.raises(ValueError, match="Truncated"):
        wwise_banks.bank_media_ids(data[:-1])
    with pytest.raises(ValueError, match="music sources"):
        wwise_banks.bank_media_ids(bank([(11, struct.pack("<II", 3, 100) + source(303))]))


@pytest.mark.parametrize("rover", ["male", "female", None])
def test_selects_authored_gender_state_with_verified_ids(tmp_path, rover):
    xml = tmp_path / "bank.xml"
    xml.write_text('''<root><object name="CAkSwitchCntr">
      <field name="eGroupType" value="1"/><field name="ulGroupID" value="3313202977"/>
      <field name="ulSwitchID" value="3111576190"/><field name="ulSwitchID" value="2204441813"/>
    </object></root>''')
    if rover is None:
        with pytest.raises(ValueError, match="authored Rover"):
            wwise_banks.rover_parameters(xml, rover)
    else:
        assert wwise_banks.rover_parameters(xml, rover) == [f"(3313202977={wwise_banks.event_id(rover)})"]


@pytest.mark.asyncio
@pytest.mark.parametrize("renditions", [0, 1, 2])
async def test_render_requires_one_authored_rendition_and_preserves_source_evidence(tmp_path, monkeypatch, renditions):
    bank = tmp_path / "play_scene.bnk"
    bank.write_bytes(b"bank")
    init = tmp_path / "Init.bnk"
    init.write_bytes(b"init")
    wem = tmp_path / "123.wem"
    wem.write_bytes(b"media")
    renderer = tmp_path / "wwiser.pyz"
    renderer.write_bytes(b"pinned renderer")
    monkeypatch.setattr(wwise_banks, "tool_path", lambda _: renderer)
    from wuwa_story_worker import cutscene_import
    monkeypatch.setattr(cutscene_import, "soundtrack_wem", lambda *_: wem)
    commands = []

    async def run(args, timeout):
        commands.append(args)
        if "-dn" in args:
            from pathlib import Path
            Path(args[args.index("-dn") + 1] + ".xml").write_text("<root/>")
        elif "-go" in args:
            from pathlib import Path
            out = Path(args[args.index("-go") + 1])
            for index in range(renditions):
                (out / f"scene-{index}.txtp").write_text(" wem/123.wem #v -3dB\n# AUTOGENERATED")
        else:
            from pathlib import Path
            Path(args[args.index("-o") + 1]).write_bytes(b"RIFF" + b"x" * 48)
        return SimpleNamespace(stderr=b"")

    if renditions != 1:
        with pytest.raises(ValueError, match="explicit non-gender selection"):
            await wwise_banks.render_bank(bank, tmp_path, tmp_path / "work", tmp_path / "decoder", "female", run)
    else:
        output, evidence = await wwise_banks.render_bank(bank, tmp_path, tmp_path / "work", tmp_path / "decoder", "female", run)
        assert output.is_file() and bank in evidence and init in evidence and wem in evidence
        assert any(path.suffix == ".txtp" for path in evidence)
        assert commands[1][commands[1].index("-gf") + 1] == str(wwise_banks.event_id("play_scene"))
        assert "-gwd" in commands[1] and "-gra" in commands[1]
