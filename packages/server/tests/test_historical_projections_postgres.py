"""Historical projection regressions on a dedicated PostgreSQL database."""

import json
import os
from pathlib import Path
from types import SimpleNamespace
from uuid import uuid4

import pytest
from sqlalchemy import delete, insert, select, text
from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine

from wuwa_story.db.models.core import Character, Item, Location
from wuwa_story.db.models.graph import Node, NodeRevision
from wuwa_story.db.models.search import SearchDocument
from wuwa_story.ingestion.canonical_import import import_canonical_entities
from wuwa_story.search.indexer import build_lexical_index

URL = os.getenv("WUWA_PROJECTION_TEST_DATABASE_URL")


def adapter(root: Path, rows):
    paths = []
    for kind, records in rows.items():
        path = root / "entities" / f"{kind}.jsonl"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(json.dumps(record) for record in records), encoding="utf-8")
        paths.append(path)
    return SimpleNamespace(root=root, entity_files=lambda: paths,
                           iter_entities=lambda kind: iter(rows.get(kind, [])))


def record(kind, identity, name, key):
    field = "title" if kind == "area" else "name"
    return {"id": f"{kind}:{identity}", "game_id": identity, field: {"en": name, "key": key},
            "raw": {}, "version": "fixture"}


@pytest.mark.asyncio
@pytest.mark.skipif(not URL, reason="Set WUWA_PROJECTION_TEST_DATABASE_URL to an isolated PostgreSQL database")
async def test_historical_import_preserves_newer_and_adds_missing_projections(tmp_path):
    base = create_async_engine(URL)
    assert base.url.database.endswith("_verification"), "Use a dedicated verification database"
    prefix = "projection_" + uuid4().hex
    schemas = {name: f"{prefix}_{name}" for name in ("ops", "graph", "core", "i18n", "search")}
    o, g, c, i, s = (schemas[name] for name in ("ops", "graph", "core", "i18n", "search"))
    engine = base.execution_options(schema_translate_map=schemas)
    factory = async_sessionmaker(engine, expire_on_commit=False, autoflush=False)
    try:
        async with base.begin() as conn:
            for schema in schemas.values():
                await conn.execute(text(f"CREATE SCHEMA {schema}"))
            for sql in (
                f"CREATE TABLE {o}.game_release (id bigint PRIMARY KEY, sequence int UNIQUE NOT NULL, game_version text NOT NULL, resource_version text, changelist bigint, upstream_name text NOT NULL, upstream_commit text, released_at timestamptz, imported_at timestamptz DEFAULT now(), metadata jsonb NOT NULL DEFAULT '{{}}')",
                f"CREATE TABLE {o}.import_run (id bigint PRIMARY KEY, release_id bigint NOT NULL, status text NOT NULL)",
                f"CREATE TABLE {g}.node_type (id smallint PRIMARY KEY, key text NOT NULL, description text)",
                f"CREATE TABLE {g}.node (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, type_id smallint, canonical_key text UNIQUE, slug text, created_release_id bigint, status text DEFAULT 'active', created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now(), metadata jsonb NOT NULL DEFAULT '{{}}')",
                f"CREATE TABLE {g}.node_revision (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, node_id bigint NOT NULL, release_id bigint, revision smallint NOT NULL, content_hash bytea, source_record_id bigint, created_at timestamptz DEFAULT now(), metadata jsonb NOT NULL DEFAULT '{{}}', UNIQUE(node_id,revision))",
                f"CREATE TABLE {c}.character (node_id bigint PRIMARY KEY, canonical_name text, name_key_id bigint, nickname_key_id bigint, description text, playable boolean, metadata jsonb NOT NULL DEFAULT '{{}}')",
                f"CREATE TABLE {c}.item (node_id bigint PRIMARY KEY, canonical_name text, name_key_id bigint, description_key_id bigint, description text, game_item_id bigint UNIQUE, metadata jsonb NOT NULL DEFAULT '{{}}')",
                f"CREATE TABLE {c}.location (node_id bigint PRIMARY KEY, canonical_name text, name_key_id bigint, game_location_id text, parent_location_node_id bigint, metadata jsonb NOT NULL DEFAULT '{{}}')",
                f"CREATE TABLE {i}.localization_key (id bigint PRIMARY KEY, key text UNIQUE)",
                f"CREATE TABLE {i}.localization_content (id bigint PRIMARY KEY, content text NOT NULL)",
                f"CREATE TABLE {i}.localization_value (release_id bigint, key_id bigint, locale_id smallint, content_id bigint, status text, PRIMARY KEY(release_id,key_id,locale_id))",
                f"CREATE TABLE {s}.document (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, target_node_id bigint, category text, locale_id smallint, title text, aliases jsonb, body text, search_vector tsvector, content_hash bytea, updated_at timestamptz DEFAULT now(), CONSTRAINT uq_search_document UNIQUE NULLS NOT DISTINCT(target_node_id,category,locale_id))",
                f"INSERT INTO {o}.game_release(id,sequence,game_version,upstream_name) VALUES (1,4,'3.4.0','fixture'),(2,2,'3.7.0','fixture'),(3,3,'3.5.0','fixture'),(4,5,'3.8.0','fixture')",
                f"INSERT INTO {o}.import_run VALUES (1,1,'succeeded'),(2,2,'succeeded'),(3,3,'running'),(4,4,'running')",
                f"INSERT INTO {g}.node_type(id,key) VALUES (1,'character'),(2,'item'),(3,'area')",
                f"INSERT INTO {i}.localization_key VALUES (1,'old'),(2,'new'),(3,'added')",
                f"INSERT INTO {i}.localization_content VALUES (1,'Old text'),(2,'Latest text'),(3,'Historical only'),(4,'Historical Japanese'),(5,'Unfinished future')",
                f"INSERT INTO {i}.localization_value VALUES (1,1,1,1,'resolved_nonempty'),(2,2,1,2,'resolved_nonempty'),(3,1,1,1,'resolved_nonempty'),(3,3,1,3,'resolved_nonempty'),(3,2,2,4,'resolved_nonempty'),(4,2,1,5,'resolved_nonempty')",
            ):
                await conn.execute(text(sql))

        kinds = {"character": Character, "item": Item, "area": Location}
        categories = {"character", "item", "area"}
        old = {kind: [record(kind, 10, "Old", "old")] for kind in kinds}
        latest = {kind: [record(kind, 20, "Latest", "new")] for kind in kinds}
        historical = {kind: [record(kind, 10, "Updated old", "added"),
                             record(kind, 20, "Must not overwrite", "old"),
                             record(kind, 30, "New historical", "added")] for kind in kinds}
        async with factory() as session:
            await import_canonical_entities(adapter(tmp_path / "old", old), session, 1, 4, batch_size=2)
            await import_canonical_entities(adapter(tmp_path / "new", latest), session, 2, 2, batch_size=2)
            await build_lexical_index(session, "3.7.0", categories=categories, release_id=2, batch_size=2)
            latest_timestamp = await session.scalar(
                select(SearchDocument.updated_at).join(Node, Node.id == SearchDocument.target_node_id)
                .where(Node.canonical_key == "character:20", SearchDocument.category == "character",
                       SearchDocument.locale_id == 1)
            )
            # An existing node may lack a search document; backfill from the
            # latest completed localization even when 3.5 has no value for it.
            missing_node = await session.scalar(select(Node.id).where(Node.canonical_key == "item:20"))
            await session.execute(delete(SearchDocument).where(SearchDocument.target_node_id == missing_node))
            await session.commit()
            await import_canonical_entities(adapter(tmp_path / "historical", historical), session, 3, 3, batch_size=2)
            await build_lexical_index(session, "3.5.0", categories=categories, release_id=3, batch_size=2)
            assert await session.scalar(
                select(SearchDocument.updated_at).join(Node, Node.id == SearchDocument.target_node_id)
                .where(Node.canonical_key == "character:20", SearchDocument.category == "character",
                       SearchDocument.locale_id == 1)
            ) == latest_timestamp

            for kind, model in kinds.items():
                rows = dict((await session.execute(select(Node.canonical_key, model.canonical_name)
                            .join(model, model.node_id == Node.id)
                            .where(Node.canonical_key.in_([f"{kind}:10", f"{kind}:20", f"{kind}:30"])))).all())
                assert rows == {f"{kind}:10": "Updated old", f"{kind}:20": "Latest", f"{kind}:30": "New historical"}
            revisions = set((await session.execute(select(Node.canonical_key, NodeRevision.release_id)
                             .join(NodeRevision, NodeRevision.node_id == Node.id))).all())
            assert len(revisions) == 15
            for kind in kinds:
                assert {(f"{kind}:10", 1), (f"{kind}:10", 3), (f"{kind}:20", 2),
                        (f"{kind}:20", 3), (f"{kind}:30", 3)} <= revisions
            docs = dict(((key, locale), body) for key, locale, body in (await session.execute(
                select(Node.canonical_key, SearchDocument.locale_id, SearchDocument.body)
                .join(SearchDocument, SearchDocument.target_node_id == Node.id)
                .where(SearchDocument.category.in_(categories)))).all())
            for kind in kinds:
                assert docs[(f"{kind}:20", 1)] == "Latest text"
                assert docs[(f"{kind}:20", 2)] == "Historical Japanese"
                assert docs[(f"{kind}:10", 1)] == "Historical only"
                assert docs[(f"{kind}:30", 1)] == "Historical only"
            await import_canonical_entities(adapter(tmp_path / "historical", historical), session, 3, 3, batch_size=2)
            await build_lexical_index(session, "3.5.0", categories=categories, release_id=3, batch_size=2)
            assert set((await session.execute(select(Node.canonical_key, NodeRevision.release_id)
                       .join(NodeRevision, NodeRevision.node_id == Node.id))).all()) == revisions
            assert dict(((key, locale), body) for key, locale, body in (await session.execute(
                select(Node.canonical_key, SearchDocument.locale_id, SearchDocument.body)
                .join(SearchDocument, SearchDocument.target_node_id == Node.id)
                .where(SearchDocument.category.in_(categories)))).all()) == docs
            # A genuinely newer import must still update the projection, and a
            # subsequent 3.5 retry must not roll it back, even before it completes.
            future = {kind: [record(kind, 20, "Future", "new")] for kind in kinds}
            await import_canonical_entities(adapter(tmp_path / "future", future), session, 4, 5, batch_size=2)
            await build_lexical_index(session, "3.8.0", categories=categories, release_id=4, batch_size=2)
            await import_canonical_entities(adapter(tmp_path / "historical", historical), session, 3, 3, batch_size=2)
            await build_lexical_index(session, "3.5.0", categories=categories, release_id=3, batch_size=2)
            for kind, model in kinds.items():
                name = await session.scalar(select(model.canonical_name).join(Node, Node.id == model.node_id)
                                            .where(Node.canonical_key == f"{kind}:20"))
                body = await session.scalar(select(SearchDocument.body).join(Node, Node.id == SearchDocument.target_node_id)
                                            .where(Node.canonical_key == f"{kind}:20", SearchDocument.locale_id == 1))
                assert (name, body) == ("Future", "Unfinished future")
            incomplete = await session.scalar(insert(Node).values(
                type_id=1, canonical_key="character:40", created_release_id=4, metadata={}
            ).returning(Node.id))
            await session.execute(insert(NodeRevision).values(
                node_id=incomplete, release_id=4, revision=5, metadata={}
            ))
            await session.commit()
            with pytest.raises(ValueError, match="newer revision has no typed projection"):
                await import_canonical_entities(
                    adapter(tmp_path / "incomplete", {"character": [record("character", 40, "Old", "old")]}),
                    session, 3, 3, batch_size=2,
                )
            assert await session.scalar(select(Character.node_id).where(Character.node_id == incomplete)) is None
            assert await session.scalar(select(NodeRevision.id).where(
                NodeRevision.node_id == incomplete, NodeRevision.release_id == 3
            )) is not None
    finally:
        await engine.dispose()
        async with base.begin() as conn:
            for schema in schemas.values():
                await conn.execute(text(f"DROP SCHEMA IF EXISTS {schema} CASCADE"))
        await base.dispose()
