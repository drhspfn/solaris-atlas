"""NPC-only revision and identity repair against isolated PostgreSQL schemas."""

import hashlib
import json
import os
from types import SimpleNamespace
from uuid import uuid4

import pytest
from sqlalchemy import select, text
from sqlalchemy.ext.asyncio import AsyncSession, create_async_engine

from wuwa_story.db.models.graph import NodeRevision
from wuwa_story.ingestion.canonical_import import _upsert_npc_revisions, import_canonical_entities
from wuwa_story.ingestion.npc_identity_repair import NAME_BASIS, repair_npc_identity

URL = os.getenv("NPC_PG_TEST_DATABASE_URL")


@pytest.mark.asyncio
@pytest.mark.skipif(not URL, reason="Set NPC_PG_TEST_DATABASE_URL to a dedicated verification database")
async def test_npc_import_changed_payload_tracks_source_across_releases(tmp_path):
    engine = create_async_engine(URL)
    assert engine.url.database.endswith("verify")
    prefix = "npc_import_" + uuid4().hex
    schemas = {name: f"{prefix}_{name}" for name in ("graph", "core", "ops", "raw", "i18n")}
    g, c, o, r, i = (schemas[name] for name in ("graph", "core", "ops", "raw", "i18n"))
    mapped = engine.execution_options(schema_translate_map=schemas)
    try:
        async with engine.begin() as conn:
            for schema in schemas.values():
                await conn.execute(text(f'CREATE SCHEMA "{schema}"'))
            for ddl in (
                f"CREATE TABLE {o}.game_release (id bigint PRIMARY KEY, sequence int, game_version text, resource_version text, changelist bigint, upstream_name text, upstream_commit text, released_at timestamptz, imported_at timestamptz DEFAULT now(), metadata jsonb DEFAULT '{{}}')",
                f"CREATE TABLE {g}.node_type (id smallint PRIMARY KEY, key text, description text)",
                f"CREATE TABLE {g}.node (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, type_id smallint, canonical_key text UNIQUE, slug text, created_release_id bigint, status text DEFAULT 'active', created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now(), metadata jsonb DEFAULT '{{}}')",
                f"CREATE TABLE {g}.node_revision (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, node_id bigint, release_id bigint, revision smallint, content_hash bytea, source_record_id bigint, created_at timestamptz DEFAULT now(), metadata jsonb DEFAULT '{{}}', UNIQUE(node_id,revision))",
                f"CREATE TABLE {c}.character (node_id bigint PRIMARY KEY, canonical_name text, name_key_id bigint, nickname_key_id bigint, description text, playable boolean, metadata jsonb)",
                f"CREATE TABLE {r}.source_file (id bigint PRIMARY KEY, release_id bigint, logical_source_path text)",
                f"CREATE TABLE {r}.source_record (id bigint PRIMARY KEY, release_id bigint, source_file_id bigint, row_index bigint, data jsonb)",
                f"CREATE TABLE {i}.localization_key (id bigint PRIMARY KEY, key text)",
                f"INSERT INTO {o}.game_release(id,sequence,game_version,upstream_name) VALUES (1,7,'3.7.0','fixture'),(2,8,'3.8.0','fixture')",
                f"INSERT INTO {g}.node_type VALUES (1,'character',NULL)",
                f"INSERT INTO {r}.source_file VALUES (1,1,'old'),(2,1,'new'),(3,2,'future')",
                f"INSERT INTO {r}.source_record VALUES (11,1,1,0,'{{}}'),(12,1,2,0,'{{}}'),(13,2,3,0,'{{}}')",
            ):
                await conn.execute(text(ddl))
        path = tmp_path / 'entities' / 'character.jsonl'
        path.parent.mkdir()
        path.touch()
        row = {"id": "character:npc:1", "game_id": 1, "raw": {}, "name": None,
               "source": {"file": "old", "row": 0}, "npc": {"blueprint_id": 1}}
        records = [row]
        adapter = SimpleNamespace(root=tmp_path, entity_files=lambda: [path],
                                  iter_entities=lambda kind: iter(records))
        def digest(value):
            return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                  separators=(',', ':'), default=str).encode()).digest()
        async with AsyncSession(mapped, expire_on_commit=False) as session:
            await import_canonical_entities(adapter, session, 1, 7)
            updated = {**row, "source": {"file": "new", "row": 0},
                       "npc": {"blueprint_id": 1, "instances": [{"entity_id": 10}]}}
            records[0] = updated
            await import_canonical_entities(adapter, session, 1, 7)
            await import_canonical_entities(adapter, session, 1, 7)
            records[0] = {**updated, "source": {"file": "future", "row": 0}}
            await import_canonical_entities(adapter, session, 2, 8)
            records[0] = updated
            await import_canonical_entities(adapter, session, 1, 7)
            revisions = (await session.execute(select(NodeRevision.__table__).order_by(
                NodeRevision.revision))).mappings().all()
            assert len(revisions) == 2
            assert (revisions[0]["content_hash"], revisions[0]["source_record_id"]) == (digest(updated), 12)
            assert revisions[0]["metadata"]["repair_history"][0]["content_hash"] == digest(row).hex()
            assert len(revisions[0]["metadata"]["repair_history"]) == 1
            assert revisions[1]["source_record_id"] == 13
            assert (await session.execute(text(f"SELECT count(*) FROM {r}.source_record"))).scalar_one() == 3
    finally:
        await mapped.dispose()
        async with engine.begin() as conn:
            for schema in schemas.values():
                await conn.execute(text(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE'))
        await engine.dispose()


@pytest.mark.asyncio
@pytest.mark.skipif(not URL, reason="Set NPC_PG_TEST_DATABASE_URL to a dedicated verification database")
async def test_npc_revision_and_identity_repair_are_scoped_and_replayable():
    engine = create_async_engine(URL)
    assert engine.url.database.endswith("verify")
    prefix = "npc_repair_" + uuid4().hex
    schemas = {name: f"{prefix}_{name}" for name in ("graph", "core", "ontology", "ops", "search")}
    g, c, o, p, s = (schemas[name] for name in ("graph", "core", "ontology", "ops", "search"))
    mapped = engine.execution_options(schema_translate_map=schemas)
    try:
        async with engine.begin() as conn:
            for schema in schemas.values():
                await conn.execute(text(f'CREATE SCHEMA "{schema}"'))
            for ddl in (
                f"CREATE TABLE {g}.node (id bigint PRIMARY KEY, canonical_key text)",
                f"CREATE TABLE {g}.node_revision (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, node_id bigint, release_id bigint, revision smallint, content_hash bytea, source_record_id bigint, created_at timestamptz DEFAULT now(), metadata jsonb DEFAULT '{{}}', UNIQUE(node_id,revision))",
                f"CREATE TABLE {o}.relation_type (id smallint PRIMARY KEY, key text)",
                f"CREATE TABLE {g}.edge (id bigint PRIMARY KEY, from_node_id bigint, relation_type_id smallint, to_node_id bigint, layer text, basis text, metadata jsonb)",
                f"CREATE TABLE {g}.edge_evidence (id bigint PRIMARY KEY, edge_id bigint REFERENCES {g}.edge(id) ON DELETE CASCADE, explanation text)",
                f"CREATE TABLE {c}.character (node_id bigint PRIMARY KEY, metadata jsonb)",
                f"CREATE TABLE {s}.document (id bigint PRIMARY KEY, target_node_id bigint, category text)",
                f"CREATE TABLE {p}.read_projection_scope (kind text, snapshot_key text, generation bigint DEFAULT 1, status text DEFAULT 'pending', published_generation bigint DEFAULT 0, updated_at timestamptz DEFAULT now(), PRIMARY KEY(kind,snapshot_key))",
                f"CREATE TABLE {p}.read_projection_dirty (kind text, entity_id bigint, snapshot_key text, requested_generation bigint DEFAULT 1, processed_generation bigint DEFAULT 0, attempts int DEFAULT 0, available_at timestamptz, PRIMARY KEY(kind,entity_id,snapshot_key))",
                f"INSERT INTO {g}.node VALUES (1,'character:npc:1'),(2,'character:npc:2'),(3,'character:3'),(4,'speaker:4')",
                f"INSERT INTO {o}.relation_type VALUES (1,'has_speaker'),(2,'presents_talk_item')",
                f"INSERT INTO {c}.character VALUES (1,'{{\"role_type\": 6,\"npc\":{{\"speakers\":[\"speaker:4\"],\"name\":\"kept\"}}}}'),(2,'{{\"role_type\": 6,\"npc\":{{\"speakers\":[]}}}}'),(3,'{{\"role_type\": 1,\"npc\":{{\"speakers\":[\"speaker:4\"]}}}}')",
                f"INSERT INTO {s}.document VALUES (1,1,'character'),(2,2,'character'),(3,3,'character')",
            ):
                await conn.execute(text(ddl))
            for edge_id, owner, relation, layer, basis, source_basis in (
                (1, 1, 1, 'source', 'explicit_reference', NAME_BASIS),
                (2, 1, 1, 'source', 'explicit_reference', NAME_BASIS),
                (3, 1, 1, 'manual', 'manual', NAME_BASIS),
                (4, 3, 1, 'source', 'explicit_reference', NAME_BASIS),
                (5, 1, 2, 'source', 'explicit_reference', NAME_BASIS),
                (6, 2, 1, 'source', 'explicit_reference', 'independent evidence'),
            ):
                await conn.execute(text(f"INSERT INTO {g}.edge VALUES (:id,:owner,:rel,4,:layer,:basis,jsonb_build_object('source_basis',CAST(:source AS text)))"),
                    dict(id=edge_id, owner=owner, rel=relation, layer=layer, basis=basis, source=source_basis))
            for identity, edge, explanation in ((1, 1, NAME_BASIS), (2, 2, NAME_BASIS),
                    (3, 2, 'independent evidence'), (4, 3, NAME_BASIS),
                    (5, 4, NAME_BASIS), (6, 5, NAME_BASIS), (7, 6, 'independent evidence')):
                await conn.execute(text(f"INSERT INTO {g}.edge_evidence VALUES (:id,:edge,:explanation)"),
                                   dict(id=identity, edge=edge, explanation=explanation))
        async with AsyncSession(mapped, expire_on_commit=False) as session:
            first = {"node_id": 1, "release_id": 7, "revision": 7, "content_hash": b"old",
                     "source_record_id": 11, "metadata": {"source_file": "old"}}
            await _upsert_npc_revisions(session, [first])
            changed = {**first, "content_hash": b"new", "source_record_id": 12,
                       "metadata": {"source_file": "new"}}
            await _upsert_npc_revisions(session, [changed])
            await _upsert_npc_revisions(session, [changed])
            revision = (await session.execute(select(NodeRevision.__table__))).mappings().one()
            assert revision["content_hash"] == b"new" and revision["source_record_id"] == 12
            assert revision["metadata"]["repair_history"] == [{"content_hash": b"old".hex(),
                "source_record_id": 11, "metadata": {"source_file": "old"}}]
            with pytest.raises(ValueError, match="different release"):
                await _upsert_npc_revisions(session, [{**changed, "release_id": 8}])
            result = await repair_npc_identity(session)
            assert result == {"affected_npcs": 1, "removed_evidence": 2,
                              "removed_edges": 1, "cleaned_metadata": 1}
            assert (await session.execute(text(f"SELECT id FROM {g}.edge ORDER BY id"))).scalars().all() == [2, 3, 4, 5, 6]
            assert (await session.execute(text(f"SELECT id FROM {g}.edge_evidence ORDER BY id"))).scalars().all() == [3, 4, 5, 6, 7]
            assert (await session.execute(text(f"SELECT metadata->'npc' FROM {c}.character WHERE node_id=1"))).scalar_one() == {"speakers": [], "name": "kept"}
            assert (await session.execute(text(f"SELECT id FROM {s}.document ORDER BY id"))).scalars().all() == [2, 3]
            assert (await session.execute(text(f"SELECT entity_id FROM {p}.read_projection_dirty ORDER BY entity_id"))).scalars().all() == [0, 1]
            assert await repair_npc_identity(session) == {"affected_npcs": 0, "removed_evidence": 0,
                                                          "removed_edges": 0, "cleaned_metadata": 0}
            await session.commit()
    finally:
        await mapped.dispose()
        async with engine.begin() as conn:
            for schema in schemas.values():
                await conn.execute(text(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE'))
        await engine.dispose()
